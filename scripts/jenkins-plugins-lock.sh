#!/usr/bin/env bash
# Resolves infrastructure/jenkins/plugins.requested.txt (+ dependencies) against the pinned
# Jenkins base image and writes the fully pinned lock to infrastructure/jenkins/plugins.txt.
# Then rebuild: docker compose build jenkins && docker compose up -d jenkins
set -euo pipefail
cd "$(dirname "$0")/../infrastructure/jenkins"
BASE="$(awk '/^FROM /{print $2; exit}' Dockerfile)"

resolved="$(docker run --rm --entrypoint bash -v "$PWD/plugins.requested.txt:/tmp/req.txt:ro" "$BASE" -c '
set -euo pipefail
jenkins-plugin-cli --plugin-file /tmp/req.txt --plugin-download-directory /tmp/p >/dev/null
cd /tmp/p
for f in *.jpi; do
  v=$(unzip -p "$f" META-INF/MANIFEST.MF | tr -d "\r" | awk -F": " "/^Plugin-Version:/{print \$2}")
  echo "${f%.jpi}:$v"
done')"

requested="$(grep -vE '^\s*(#|$)' plugins.requested.txt | cut -d: -f1)"
{
  echo "# GENERATED by scripts/jenkins-plugins-lock.sh from plugins.requested.txt - do not edit by hand."
  echo "# Base image: $BASE"
  echo "# --- requested plugins"
  for p in $requested; do grep "^$p:" <<<"$resolved"; done
  echo "# --- transitive dependencies (lock)"
  grep -vxF -f <(for p in $requested; do grep "^$p:" <<<"$resolved"; done) <<<"$resolved" | sort
} >plugins.txt
echo "plugins.txt: $(grep -vc '^#' plugins.txt) plugins pinned"
